"""Generate typed presentation constants from the stable, provisional glossary.

This does not rewrite operational records or translate arbitrary user data.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESERVED = set('assert break case catch class const continue default do else enum extends false final finally for if in is new null rethrow return super switch this throw true try var void while with'.split())


def dart_identifier(key):
    # Keep persisted semantic keys stable; only the generated language symbol
    # changes when an English-derived name happens to be a Dart keyword.
    return key + 'Message' if key in RESERVED else key


def literal(value):
    # JSON quoting is Dart-compatible after preventing Dart interpolation.
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def main():
    widget_path = ROOT / 'app/lib/app/bilingual.dart'
    widget_source = widget_path.read_text(encoding='utf-8')
    if 'abstract final class L10n' in widget_source:
        start = widget_source.index('/// Stable typed')
        end = widget_source.index('/// LTR chrome;')
        (ROOT / 'app/lib/app/bilingual_message.dart').write_text(
            widget_source[start:end], encoding='utf-8')
        widgets = widget_source[end:widget_source.index('abstract final class L10n')]
        widget_path.write_text(
            "import 'package:flutter/material.dart';\n"
            "import 'bilingual_message.dart';\n"
            "export 'bilingual_message.dart';\n"
            "export 'ui_catalogue.dart';\n\n" + widgets, encoding='utf-8')
    entries = json.loads((ROOT / 'tools/karvaan/phrases.json').read_text(encoding='utf-8'))
    keys, semantic_keys = set(), set()
    for entry in entries:
        if not re.fullmatch(r'[a-zA-Z_][a-zA-Z0-9_]*', entry['key']):
            raise ValueError('Invalid Dart identifier: ' + entry['key'])
        if entry['key'] in keys or entry['semantic_key'] in semantic_keys:
            raise ValueError('Duplicate stable key: ' + entry['key'])
        keys.add(entry['key'])
        semantic_keys.add(entry['semantic_key'])
        if not entry['ur']:
            raise ValueError('Missing translation: ' + entry['key'])
        if sorted(re.findall(r'\{[0-9]+\}', entry['en'])) != sorted(re.findall(r'\{[0-9]+\}', entry['ur'])):
            raise ValueError('Placeholder mismatch: ' + entry['key'])
        if re.search('[۰-۹٠-٩]', entry['ur']):
            raise ValueError('Non-Latin digits: ' + entry['key'])
    source = ['// Generated by tools/karvaan/generate_catalogue.py. Office review pending.',
              "import 'bilingual_message.dart';", '', 'abstract final class L10n {']
    for entry in entries:
        source.append('  static const ' + dart_identifier(entry['key']) + '=Bilingual(' + ','.join(
            literal(entry[name]) for name in ('semantic_key', 'en', 'ur')) + ');')
        source.append('  static const ' + dart_identifier(entry['key']) + 'Accessibility=' +
                      literal(entry['en'] + '. ' + entry['ur']) + ';')
    source.append('  static const values=<Bilingual>[')
    source.extend('    ' + dart_identifier(entry['key']) + ',' for entry in entries)
    source.extend(['  ];', '}', ''])
    target = ROOT / 'app/lib/app/ui_catalogue.dart'
    target.write_text('\n'.join(source), encoding='utf-8')
    print(f'Generated {len(entries)} typed bilingual messages; office review pending.')


if __name__ == '__main__':
    main()
